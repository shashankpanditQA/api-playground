'use strict';
// Builds the Postman collection from src/challenges.js. Run with: npm run postman
const fs = require('fs');
const path = require('path');
const challenges = require('../src/challenges');

const toPostman = (text) => text.replace(/\{\{uuid\}\}/g, '{{$guid}}').replace(/\{\{now\}\}/g, '{{$timestamp}}');

function buildItem(step, { name, isFirst, assertStatus }) {
  const prerequest = [];
  if (isFirst) prerequest.push("pm.collectionVariables.set('idemKey', 'pm-' + pm.variables.replaceIn('{{$guid}}'));");
  if (step.waitMs) prerequest.push(`setTimeout(() => {}, ${step.waitMs});`);

  const tests = [];
  if (assertStatus) {
    const allowed = JSON.stringify([].concat(step.expect));
    tests.push(`pm.test('Status is ${[].concat(step.expect).join(' or ')}', () => pm.expect(${allowed}).to.include(pm.response.code));`);
    for (const [h, v] of Object.entries(step.expectHeaders || {})) {
      tests.push(`pm.test('Header ${h}', () => pm.expect(pm.response.headers.get(${JSON.stringify(h)})).to.eql(${JSON.stringify(v)}));`);
    }
  }
  for (const [variable, field] of Object.entries(step.capture || {})) {
    tests.push(`pm.collectionVariables.set(${JSON.stringify(variable)}, pm.response.json()[${JSON.stringify(field)}]);`);
  }
  for (const [variable, header] of Object.entries(step.captureHeaders || {})) {
    tests.push(`pm.collectionVariables.set(${JSON.stringify(variable)}, pm.response.headers.get(${JSON.stringify(header)}));`);
  }

  const headers = { ...(step.headers || {}) };
  const hasBody = step.body !== undefined || step.bodyRaw !== undefined;
  if (hasBody && !Object.keys(headers).some((h) => h.toLowerCase() === 'content-type')) headers['Content-Type'] = 'application/json';
  const [rawPath, rawQuery] = toPostman(step.path).split('?');

  const request = {
    method: step.method,
    header: Object.entries(headers).map(([key, value]) => ({ key, value: toPostman(value) })),
    url: {
      raw: `{{baseUrl}}${toPostman(step.path)}`,
      host: ['{{baseUrl}}'],
      path: rawPath.split('/').filter(Boolean),
      ...(rawQuery ? { query: rawQuery.split('&').map((pair) => { const [key, value] = pair.split('='); return { key, value }; }) } : {}),
    },
  };
  if (hasBody) request.body = { mode: 'raw', raw: step.bodyRaw ?? toPostman(JSON.stringify(step.body, null, 2)) };

  const event = [];
  if (prerequest.length) event.push({ listen: 'prerequest', script: { type: 'text/javascript', exec: prerequest } });
  if (tests.length) event.push({ listen: 'test', script: { type: 'text/javascript', exec: tests } });
  return { name, request, event };
}

const tracks = new Map();
for (const c of challenges) {
  if (!tracks.has(c.track)) tracks.set(c.track, []);
  const items = [];
  c.steps.forEach((step, i) => {
    const copies = step.repeat || 1;
    for (let n = 1; n <= copies; n += 1) {
      items.push(buildItem(step, {
        name: copies > 1 ? `${step.name} (${n} of ${copies})` : step.name,
        isFirst: i === 0 && n === 1,
        assertStatus: n === copies,
      }));
    }
  });
  const description = `${c.task}\n\nHint: ${c.hint}${c.steps.some((s) => s.parallel) ? '\n\nPostman sends one request at a time, so send this from two tabs within 3 seconds, or use "Send twice at once" in the web console.' : ''}`;
  tracks.get(c.track).push({ name: c.title, description, item: items });
}

const collection = {
  info: {
    name: 'API Playground',
    description: 'Practice challenges for the local API Playground. Start the server, then run this collection or a folder. Generated by npm run postman.',
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
  },
  variable: [
    { key: 'baseUrl', value: 'http://localhost:3000' },
    { key: 'apiKey', value: 'pk_test_playground' },
  ],
  item: [...tracks].map(([name, item]) => ({ name, item })),
};

const out = path.join(__dirname, '..', 'postman', 'api-playground.postman_collection.json');
fs.writeFileSync(out, `${JSON.stringify(collection, null, 2)}\n`);
console.log(`Wrote ${out}`);
